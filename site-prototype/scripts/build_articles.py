"""One manuscript registry drives rendering, routing, discovery and observation.

Usage: python scripts/build_articles.py [--check]
Manuscripts in content/articles/*.md are the only editable article records.
"""
import argparse
from datetime import date
import json
from pathlib import Path
import re
import sys

from markdown_it import MarkdownIt
import yaml

def require(condition, message):
    if not condition:
        raise ValueError(message)

ROOT = Path(__file__).resolve().parents[1]
LEGACY = {"agent-traps": ("/agent-traps.html", "agent_traps"),
          "agents-and-traps": ("/agents-and-traps.html", "agents_and_traps"),
          "owed-approved-urgent": ("/owed-approved-urgent.html", "research:owed-approved-urgent")}
RESERVED = {"index", "about", "research", "muse", "guestbook", "responses", "receipt", "participate", "send", "respond", "leave-a-message", "unfinished-outputs", "observations", "observations-detail", "guestbook-complete"}

class UniqueLoader(yaml.SafeLoader):
    pass

def mapping(loader, node):
    result = {}
    for key, value in node.value:
        key = loader.construct_object(key)
        require(isinstance(key, str) and key not in result, "Duplicate metadata key")
        result[key] = loader.construct_object(value)
    return result
UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping)

def catalog(root=ROOT):
    articles, seen, paths, numbers = [], set(), set(), set()
    md = MarkdownIt("commonmark", {"html": False, "typographer": False}).enable("table")
    for path in sorted((root / "content/articles").glob("*.md")):
        source = path.read_text(encoding="utf-8-sig")
        match = re.fullmatch(r"---\r?\n(.*?)\r?\n---\r?\n(.*)", source, re.S)
        require(match, f"Missing metadata: {path.name}")
        meta, body = yaml.load(match[1], Loader=UniqueLoader), match[2]
        allowed = {"section", "number", "slug", "title", "summary", "date", "last_updated", "topic_selected_by", "byline"}
        require(isinstance(meta, dict) and not set(meta) - allowed, "Unknown article fields")
        slug, section = meta.get("slug"), meta.get("section")
        require(isinstance(slug, str) and re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug)
                and slug not in seen and slug not in RESERVED, "Duplicate or invalid article ID")
        require(section in {"muse", "research"}, "Invalid section")
        for field in ("title", "summary", "byline"):
            require(isinstance(meta.get(field), str) and meta[field].strip()
                    and not any(ord(c) < 32 for c in meta[field]), f"Invalid {field}")
        for field in ("date", "last_updated"):
            if isinstance(meta.get(field), date):
                meta[field] = meta[field].isoformat()
            require(meta.get(field) is None or (isinstance(meta[field], str)
                    and re.fullmatch(r"\d{4}-\d{2}-\d{2}", meta[field])), "Invalid date")
            if meta.get(field):
                date.fromisoformat(meta[field])
        number = meta.get("number")
        require(number is None or (type(number) is int and number > 0 and (section, number) not in numbers), "Invalid/duplicate article number")
        numbers.add((section, number))
        url, page = LEGACY.get(slug, (f"/{section}/{slug}.html", f"{section}:{slug}"))
        require(url not in paths and body.strip(), "Duplicate URL or empty article")
        tokens = md.parse(body)
        require(not any(t.type == "heading_open" and t.tag == "h1" for t in tokens), "Use H2 or lower; template supplies title")
        ids = set()
        for i, token in enumerate(tokens):
            if token.type == "heading_open":
                label = tokens[i+1].content
                base = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-") or "section"
                anchor, n = base, 2
                while anchor in ids:
                    anchor, n = f"{base}-{n}", n+1
                ids.add(anchor)
                token.attrSet("id", anchor)
            if token.type == "th_open":
                token.attrSet("scope", "col")
        html = md.renderer.render(tokens, md.options, {})
        html = html.replace("<table>", '<div class="table-scroll" role="region" aria-label="Article table" tabindex="0"><table>').replace("</table>", "</table></div>")
        articles.append({**meta, "path": url, "page": page, "html": html})
        seen.add(slug); paths.add(url)
    require(articles, "No registered articles")
    return articles

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/articles.generated.js"
    rendered = "// Generated by scripts/build_articles.py. Edit content/articles/*.md.\nexport const ARTICLES = " + json.dumps(catalog(), ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        require(output.exists() and output.read_text(encoding="utf-8") == rendered, "Article bundle is stale; run scripts/build_articles.py")
    else:
        output.write_text(rendered, encoding="utf-8", newline="\n")
    print("Article registry verified" if args.check else "Article registry built")

if __name__ == "__main__":
    try:
        main()
    except (ValueError, yaml.YAMLError) as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(1)
