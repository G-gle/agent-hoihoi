"""Build approved Markdown notes and discovery files without deploying anything."""

import argparse
from datetime import date
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys
import unicodedata
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/build_research.py; edit the Markdown source."
RESERVED = {"index", "research", "about", "observations", "observations-detail",
            "guestbook", "guestbook-complete"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def text(value, field):
    require(isinstance(value, str) and value.strip() and not any(
        ord(c) < 32 for c in value), f"{field} must be nonempty, single-line text")
    return value


def validate_record(record):
    require(isinstance(record, dict), "Article metadata must be an object")
    for key in ("title", "summary", "slug"):
        text(record.get(key), key)
    require(re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", record["slug"])
            and record["slug"] not in RESERVED, "Invalid or reserved article slug")
    require(type(record.get("number")) is int and record["number"] > 0,
            "number must be a positive integer")


def manuscript(path):
    try:
        import yaml
    except ImportError as exc:
        raise ValueError("Install requirements-research.txt before building articles") from exc

    class UniqueLoader(yaml.SafeLoader):
        pass

    def mapping(loader, node):
        result = {}
        for key_node, value_node in node.value:
            key = loader.construct_object(key_node)
            require(isinstance(key, str) and key not in result,
                    f"Duplicate or invalid metadata key in {path.name}")
            result[key] = loader.construct_object(value_node)
        return result

    UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping)
    source = path.read_text(encoding="utf-8-sig")
    match = re.match(r"\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z", source, re.S)
    require(match, f"{path.name}: expected YAML metadata between --- lines")
    try:
        meta = yaml.load(match[1], Loader=UniqueLoader)
    except yaml.YAMLError as exc:
        raise ValueError(f"{path.name}: invalid YAML metadata: {exc}") from exc
    validate_record(meta)
    allowed = {"number", "slug", "title", "summary", "date", "byline", "status"}
    require(not set(meta) - allowed, f"{path.name}: unknown metadata fields: {set(meta) - allowed}")
    require(meta.get("status", "draft") in {"draft", "published"},
            f"{path.name}: status must be draft or published")
    if isinstance(meta.get("date"), date):
        meta["date"] = meta["date"].isoformat()
    require(isinstance(meta.get("date"), str) and
            re.fullmatch(r"\d{4}-\d{2}-\d{2}", meta["date"]), f"{path.name}: date must be YYYY-MM-DD")
    date.fromisoformat(meta["date"])
    if "byline" in meta:
        text(meta["byline"], "byline")
    require(match[2].strip(), f"{path.name}: empty manuscript")
    return meta, match[2]


def substitute(template, values):
    """Substitute once, so manuscript text cannot become another placeholder."""
    def replace(match):
        key = match[1]
        require(key in values, f"Unknown template field: {key}")
        return values[key]
    return re.sub(r"\{\{([A-Z_]+)\}\}", replace, template)


def article_page(root, meta, body):
    try:
        from markdown_it import MarkdownIt
    except ImportError as exc:
        raise ValueError("Install requirements-research.txt before building articles") from exc
    md = MarkdownIt("commonmark", {"html": False, "typographer": False}).enable("table")
    tokens = md.parse(body)
    # A matching leading title is accepted; all other H1s are errors.
    if tokens and tokens[0].type == "heading_open" and tokens[0].tag == "h1":
        require(tokens[1].content == meta["title"], "Body title differs from metadata title")
        tokens = tokens[3:]
    require(not any(t.type == "heading_open" and t.tag == "h1" for t in tokens),
            "Use H2 or lower in the article body; the template supplies the H1")
    require(tokens, "Article contains only a title")
    ids = {"main", "research-article"}
    toc = []
    for index, token in enumerate(tokens):
        if token.type == "heading_open":
            heading = tokens[index + 1]
            label = "".join(t.content for t in (heading.children or [])
                            if t.type in {"text", "code_inline"})
            base = re.sub(r"[^a-z0-9]+", "-", unicodedata.normalize(
                "NFKD", label).encode("ascii", "ignore").decode().lower()).strip("-") or "section"
            anchor, suffix = base, 2
            while anchor in ids:
                anchor, suffix = f"{base}-{suffix}", suffix + 1
            ids.add(anchor)
            token.attrSet("id", anchor)
            if token.tag in {"h2", "h3"}:
                css = ' class="toc-subheading"' if token.tag == "h3" else ""
                toc.append(f'          <a{css} href="#{anchor}">{escape(label)}</a>')
        if token.type == "th_open":
            token.attrSet("scope", "col")
    def table_open(renderer, items, index, options, env):
        return '<div class="table-scroll" role="region" aria-label="Article table" tabindex="0">\n<table>\n'
    def table_close(renderer, items, index, options, env):
        return '</table>\n</div>\n'
    md.add_render_rule("table_open", table_open)
    md.add_render_rule("table_close", table_close)
    article = md.renderer.render(tokens, md.options, {})
    return substitute((root / "templates/article.html").read_text(encoding="utf-8"), {
        "TITLE": escape(meta["title"], quote=True), "SUMMARY": escape(meta["summary"], quote=True),
        "NUMBER": f'{meta["number"]:02d}', "DATE": meta["date"],
        "BYLINE": " · " + escape(meta["byline"]) if meta.get("byline") else "",
        "TOC": "\n".join(toc), "ARTICLE": article.rstrip(),
    })


class Links(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.ids, self.links = set(), []
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if "id" in attrs:
            require(attrs["id"] not in self.ids, f'Duplicate HTML id: {attrs["id"]}')
            self.ids.add(attrs["id"])
        for key in ("href", "src"):
            if key in attrs:
                self.links.append((tag, key, attrs[key]))


def validate_links(root, outputs, deleted):
    public = (root / "public").resolve()
    parsed = {path.name: Links(source) for path, source in outputs.items() if path.suffix == ".html"}
    for name, page in list(parsed.items()):
        for tag, key, href in page.links:
            link = urlsplit(href)
            if link.scheme or link.netloc:
                require(tag == "a" and key == "href" and link.scheme == "https" and link.hostname,
                        f"{name}: only HTTPS external links are supported: {href}")
                continue
            require(href and not href.startswith("//"), f"{name}: empty or protocol-relative URL")
            target = (public / unquote(link.path)).resolve() if link.path else public / name
            require(target.is_relative_to(public) and target not in deleted and
                    (target in outputs or target.is_file()), f"{name}: broken local link: {href}")
            if link.fragment:
                destination = parsed.get(target.name)
                if destination is None:
                    destination = Links(target.read_text(encoding="utf-8"))
                require(unquote(link.fragment) in destination.ids, f"{name}: broken fragment: {href}")


def sitemap_pages(articles):
    return ["", "research.html", *[a["slug"] + ".html" for a in articles], "about.html"]


def build(root=ROOT, check=False):
    root = root.resolve()
    public = root / "public"
    articles = json.loads((root / "content/research-legacy.json").read_text(encoding="utf-8"))
    require(isinstance(articles, list), "Legacy catalog must be a list")
    for article in articles:
        validate_record(article)
        article["generated"] = False
        require((public / (article["slug"] + ".html")).is_file(), "Missing legacy article page")
    outputs, all_records = {}, list(articles)
    for path in sorted((root / "content/research").glob("*.md")):
        if path.name == "README.md":
            continue
        meta, body = manuscript(path)
        all_records.append(meta)
        if meta.get("status", "draft") != "published":
            continue
        article = {k: meta[k] for k in ("number", "slug", "title", "summary")}
        article["generated"] = True
        articles.append(article)
        outputs[public / (meta["slug"] + ".html")] = article_page(root, meta, body)
    for key in ("number", "slug"):
        values = [a[key] for a in all_records]
        require(len(values) == len(set(values)), f"Duplicate article {key}, including drafts")
    articles.sort(key=lambda a: a["number"])
    catalog = root / "content/research-index.json"
    previous = json.loads(catalog.read_text(encoding="utf-8")) if catalog.exists() else []
    require(isinstance(previous, list), "Invalid previous generated catalog")
    for record in previous:
        validate_record(record)
    owned = {public / (a["slug"] + ".html") for a in previous if a.get("generated") is True}
    for path in outputs:
        require(not path.exists() or path in owned, f"Refusing to overwrite unmanaged file: {path.name}")
    deleted = {path for path in owned - outputs.keys() if path.exists()}
    for path in deleted:
        require(MARKER in path.read_text(encoding="utf-8"), f"Refusing to delete unmanaged page: {path.name}")
    entries, links = [], []
    for a in articles:
        e = {key: escape(a[key], quote=True) for key in ("slug", "title", "summary")}
        entries.append(f'        <section class="research-entry"><span class="note-number">{a["number"]:02d}</span><div><h2><a href="{e["slug"]}.html">{e["title"]}</a></h2>\n'
                       f'          <p>{e["summary"]}</p>\n        </div>\n        </section>')
        label = a["title"].replace("\\", "\\\\").replace("[", r"\[").replace("]", r"\]")
        summary = a.get("discovery_summary", a["summary"])
        links.append(f'- [{label}]({a["slug"]}.html): {summary}')
    outputs[public / "research.html"] = substitute((root / "templates/research.html").read_text(encoding="utf-8"),
                                                  {"RESEARCH_ENTRIES": "\n".join(entries)})
    outputs[public / "llms.txt"] = substitute((root / "templates/llms.txt").read_text(encoding="utf-8"),
                                             {"RESEARCH_LINKS": "\n".join(links)})
    from write_sitemap import render_sitemap
    config = json.loads((root / "site.config.json").read_text(encoding="utf-8"))
    base = config.get("publicBaseUrl") or config["localBaseUrl"]
    outputs[public / "sitemap.xml"] = render_sitemap(base, sitemap_pages(articles), bool(config.get("publicBaseUrl")))
    validate_links(root, outputs, deleted)
    outputs[catalog] = json.dumps(articles, ensure_ascii=False, indent=2) + "\n"
    changed = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data.encode("utf-8")]
    if check:
        require(not changed and not deleted, "Generated research files are out of date: " +
                ", ".join(str(p.relative_to(root)) for p in sorted(set(changed) | deleted)))
    else:
        # Parse and validate every manuscript, output, and link before changing files.
        for path in changed:
            path.write_bytes(outputs[path].encode("utf-8"))
        for path in deleted:
            path.unlink()
    return len(articles), len(changed), len(deleted)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale output without changing files")
    args = parser.parse_args()
    try:
        count, changed, deleted = build(check=args.check)
    except (ValueError, OSError) as exc:
        parser.exit(1, f"Research build failed: {exc}\n")
    print(f'Research {"check" if args.check else "build"}: {count} articles, {changed} changed, {deleted} removed.')


if __name__ == "__main__":
    main()
